-- Script completo para configurar la base de datos en Supabase

CREATE TABLE IF NOT EXISTS public.departamentos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL UNIQUE,
  codigo character varying UNIQUE
);

CREATE TABLE IF NOT EXISTS public.municipios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL,
  departamento_id integer NOT NULL,
  codigo character varying UNIQUE,
  CONSTRAINT municipios_departamento_id_fkey
    FOREIGN KEY (departamento_id) REFERENCES public.departamentos(id)
);

CREATE TABLE IF NOT EXISTS public.instituciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL,
  telefono character varying,
  correo character varying,
  direccion character varying,
  naturaleza text NOT NULL,
  municipio_id integer NOT NULL,
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  eliminado_en timestamp without time zone,
  CONSTRAINT instituciones_municipio_id_fkey
    FOREIGN KEY (municipio_id) REFERENCES public.municipios(id)
);

CREATE TABLE IF NOT EXISTS public.grados (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL UNIQUE,
  orden integer
);

CREATE TABLE IF NOT EXISTS public.roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL UNIQUE,
  esta_activo boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo character varying NOT NULL UNIQUE,
  contrasena_hash character varying NOT NULL,
  esta_activo boolean NOT NULL DEFAULT true,
  debe_cambiar_contrasena boolean NOT NULL DEFAULT false,
  token_fcm character varying,
  ultimo_ingreso timestamp without time zone,
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  eliminado_en timestamp without time zone,
  rol_id integer NOT NULL,
  CONSTRAINT usuarios_rol_id_fkey
    FOREIGN KEY (rol_id) REFERENCES public.roles(id)
);

CREATE TABLE IF NOT EXISTS public.cursos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL,
  grado_id integer NOT NULL,
  jornada text NOT NULL,
  institucion_id integer NOT NULL,
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT cursos_grado_id_fkey
    FOREIGN KEY (grado_id) REFERENCES public.grados(id),
  CONSTRAINT cursos_institucion_id_fkey
    FOREIGN KEY (institucion_id) REFERENCES public.instituciones(id)
);

CREATE TABLE IF NOT EXISTS public.categorias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL UNIQUE,
  descripcion text,
  color character varying,
  icono character varying
);

CREATE TABLE IF NOT EXISTS public.periodos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre character varying NOT NULL,
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  institucion_id integer NOT NULL,
  esta_activo boolean NOT NULL DEFAULT false,
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT periodos_institucion_id_fkey
    FOREIGN KEY (institucion_id) REFERENCES public.instituciones(id)
);

