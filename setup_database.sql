-- Uniques (solo si no existen). OJO: en Postgres no existe "ADD CONSTRAINT IF NOT EXISTS" en todas las versiones,
-- entonces lo manejamos con DO $$.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'instituciones_codigo_dane_key'
  ) THEN
    ALTER TABLE public.instituciones
      ADD CONSTRAINT instituciones_codigo_dane_key UNIQUE (codigo_dane);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'instituciones_nit_key'
  ) THEN
    ALTER TABLE public.instituciones
      ADD CONSTRAINT instituciones_nit_key UNIQUE (nit);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'instituciones_estrato_check'
  ) THEN
    ALTER TABLE public.instituciones
      ADD CONSTRAINT instituciones_estrato_check CHECK (estrato >= 1 AND estrato <= 6);
  END IF;
END$$;

