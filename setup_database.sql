CREATE TABLE IF NOT EXISTS public.funcionarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  nombre character varying(255) NOT NULL,
  apellido character varying(255) NOT NULL,
  telefono character varying(20),
  correo_institucional character varying(255),
  direccion character varying(255),

  rol_id integer NOT NULL,
  usuario_id integer NOT NULL,
  institucion_id integer NULL,

  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  eliminado_en timestamp without time zone NULL,

  CONSTRAINT funcionarios_rol_id_fkey
    FOREIGN KEY (rol_id) REFERENCES public.roles(id) ON UPDATE CASCADE ON DELETE RESTRICT,

  CONSTRAINT funcionarios_usuario_id_fkey
    FOREIGN KEY (usuario_id) REFERENCES public.usuarios(id) ON UPDATE CASCADE ON DELETE RESTRICT,

  CONSTRAINT funcionarios_institucion_id_fkey
    FOREIGN KEY (institucion_id) REFERENCES public.instituciones(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 1:1 usuario <-> funcionario
CREATE UNIQUE INDEX IF NOT EXISTS funcionarios_usuario_id_unique ON public.funcionarios (usuario_id);

